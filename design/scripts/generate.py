#!/usr/bin/env python3
"""Generate platform files from design/tokens.json.

    python3 design/scripts/generate.py          # write design/generated/*
    python3 design/scripts/generate.py --check  # exit 1 if generated files are stale

Outputs:
    design/generated/WeirnoteTokens.swift  SwiftUI colours and metrics for the Apple apps
    apps/apple/Sources/Weirnote/WeirnoteTokens.swift  Mac app copy of those tokens

tokens.json is the only source of truth. Never edit the generated files by hand.
Standard library only.
"""
import json
import re
import sys
from pathlib import Path

DESIGN = Path(__file__).resolve().parent.parent
TOKENS = DESIGN / "tokens.json"
OUT = DESIGN / "generated"
HEADER = "Generated by design/scripts/generate.py from design/tokens.json. Do not edit."


def theme_values(token, themes):
    v = token["value"]
    if isinstance(v, str):
        return {t: v for t in themes}
    first = v.get(themes[0])
    return {t: v.get(t, first) for t in themes}


HEX = re.compile(r"^#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?$")


def swift_rgba(value):
    m = HEX.match(value)
    if not m:
        return None  # rgba()/shadows are web-only
    h = m.group(1)
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    a = int(m.group(2), 16) / 255 if m.group(2) else 1.0
    return f"red: {r:.4f}, green: {g:.4f}, blue: {b:.4f}, alpha: {a:.4f}"


def camel(name):
    parts = re.split(r"[-_.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def swift(tokens):
    themes = [t["id"] for t in tokens["color"]["themes"]]
    light, dark = themes[0], themes[1]
    colors = ""
    for t in tokens["color"]["tokens"]:
        vals = theme_values(t, themes)
        lo, hi = swift_rgba(vals[light]), swift_rgba(vals[dark])
        if not (lo and hi):
            continue
        usage = t.get("usage", "").replace("\n", " ")
        colors += f"    /// {usage}\n    static let {camel(t['name'])} = Color(light: .init({lo}), dark: .init({hi}))\n\n"
    metrics = ""
    for fam in ("spacing", "radius"):
        for t in tokens.get(fam, {}).get("tokens", []):
            metrics += f"    static let {camel(t['name'])}: CGFloat = {float(str(t['value']).rstrip('px'))}\n"
    for t in tokens.get("depth", {}).get("tokens", []):
        metrics += f"    static let {camel(t['name'])}: CGFloat = {float(t['value'])}\n"

    for name, value in tokens["type"].get("native", {}).items():
        metrics += f"    static let {camel(name)}: CGFloat = {float(value)}\n"

    shadows = ""
    for t in tokens.get("shadow", {}).get("tokens", []):
        if native := t.get("native"):
            lo, hi = swift_rgba(native[light]), swift_rgba(native[dark])
            shadows += (f"    /// {t.get('usage', '')}\n"
                        f"    static let {camel(t['name'])} = Style(color: Color(light: .init({lo}), dark: .init({hi})), "
                        f"radius: {native['radius']}, x: {native['x']}, y: {native['y']})\n")

    return f"""// {HEADER}

import SwiftUI
#if canImport(AppKit)
import AppKit
private typealias PlatformColor = NSColor
#else
import UIKit
private typealias PlatformColor = UIColor
#endif

private extension Color {{
    struct RGBA {{ let red, green, blue, alpha: Double }}

    init(light: RGBA, dark: RGBA) {{
        func make(_ c: RGBA) -> PlatformColor {{
            #if canImport(AppKit)
            PlatformColor(srgbRed: c.red, green: c.green, blue: c.blue, alpha: c.alpha)
            #else
            PlatformColor(red: c.red, green: c.green, blue: c.blue, alpha: c.alpha)
            #endif
        }}
        #if canImport(AppKit)
        self.init(nsColor: NSColor(name: nil) {{ appearance in
            appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? make(dark) : make(light)
        }})
        #else
        self.init(uiColor: UIColor {{ traits in
            traits.userInterfaceStyle == .dark ? make(dark) : make(light)
        }})
        #endif
    }}
}}

/// Weirnote brand colours. Use for content (note text, paper backgrounds) and
/// the accent; leave system chrome to the system's own colours.
enum WeirnoteColor {{
{colors.rstrip()}
}}

/// Spacing, radii and the selected-note lift, in points.
enum WeirnoteMetric {{
{metrics.rstrip()}
}}

/// Explicit custom shadows; system controls otherwise own their own depth.
enum WeirnoteShadow {{
    struct Style {{
        let color: Color
        let radius, x, y: CGFloat
    }}
{shadows.rstrip()}
}}
"""


def main():
    tokens = json.loads(TOKENS.read_text())
    outputs = {OUT / "WeirnoteTokens.swift": swift(tokens)}
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"stale: {p.relative_to(DESIGN.parent)}")
        sys.exit(1 if stale else 0)
    OUT.mkdir(exist_ok=True)
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print(f"wrote {p.relative_to(DESIGN.parent)}")


if __name__ == "__main__":
    main()
